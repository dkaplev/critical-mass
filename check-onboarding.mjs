import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {campaign} from './dist/campaign.mjs';
import {resolve,bound} from './dist/engine.mjs';
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const first=campaign[0],opening=resolve(first.n,first.orbs,first.hintTap);
assert.equal(opening.bursts,7);assert.equal(opening.waves.length,6);
assert(first.targets.every(i=>opening.odometer[i]>0));
assert(first.orbs.reduce((a,b)=>a+b,0)+first.budget<bound(first.n));
for(const tile of first.targets){const r=resolve(first.n,first.orbs,tile);assert(r.bursts>=5&&r.bursts<=7);assert(first.targets.every(i=>r.odometer[i]>0))}
const server=createServer(async(req,res)=>{try{const path=req.url==='/'?'index.html':req.url.slice(1);if(!/^[a-z0-9.-]+$/i.test(path))throw Error('Invalid path');const data=await readFile(new URL('./dist/'+path,import.meta.url));res.setHeader('Content-Type',path.endsWith('.mjs')?'text/javascript':path.endsWith('.css')?'text/css':path.endsWith('.svg')?'image/svg+xml':'text/html');res.end(data)}catch{res.writeHead(404);res.end()}});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE,args:['--no-sandbox','--disable-dev-shm-usage']});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.clock.install({time:new Date('2026-10-07T08:00:00Z')});
await page.clock.pauseAt(new Date('2026-10-07T08:00:01Z'));
const hinted=()=>page.locator('.cell.first-tap-hint').count();
try{
 await page.goto(process.env.GAME_URL||`http://127.0.0.1:${server.address().port}`,{waitUntil:'domcontentloaded'});
 await page.locator('#introPlay').waitFor();
 assert.equal(await page.locator('#modal h2').textContent(),'How to play');
 await page.clock.runFor(5000);assert.equal(await hinted(),0,'No hint while intro is open');
 await page.locator('#introPlay').click();assert.equal(await page.locator('#modal').evaluate(e=>e.open),false,'Only one opening popup');
 await page.clock.runFor(3999);assert.equal(await hinted(),0);
 await page.clock.runFor(1);assert.equal(await hinted(),1,'Hint appears at four seconds');
 assert.equal(await page.locator('.first-tap-hint').getAttribute('data-i'),'0');
 await page.screenshot({path:'/tmp/critical-mass-tutorial-arrow.png'});
 await page.locator('#settings').click();assert.equal(await hinted(),0);
 await page.clock.runFor(5000);assert.equal(await hinted(),0,'No hint behind pause');
 await page.locator('#resume').click();await page.clock.runFor(3999);assert.equal(await hinted(),0);
 await page.clock.runFor(1);assert.equal(await hinted(),1);
 await page.locator('#board [data-i="0"]').click();assert.equal(await hinted(),0);
 await page.clock.runFor(4000);
 assert.equal(await page.locator('#modal h2').textContent(),'Level complete!');
 assert.deepEqual(await page.locator('.result-stats strong').allTextContents(),['1','1','7']);
 await page.locator('#retry').click();await page.clock.runFor(5000);assert.equal(await hinted(),0,'No hint on replay');
 await page.locator('#board [data-i="8"]').click();await page.clock.runFor(500);await page.locator('#undo').click();await page.clock.runFor(5000);assert.equal(await hinted(),0,'Undo does not revive hint');
 await page.reload({waitUntil:'domcontentloaded'});await page.locator('#board .cell').first().waitFor();await page.clock.runFor(5000);assert.equal(await hinted(),0,'First tap acknowledgement survives reload');
 await page.locator('#progress [data-level="1"]').click();assert.equal(await page.locator('#modal h2').textContent(),'Ready to burst');await page.locator('#introPlay').click();await page.clock.runFor(5000);assert.equal(await hinted(),0,'No hint on later levels');
 const reducedContext=await browser.newContext({viewport:{width:320,height:740},reducedMotion:'reduce'});
 const p=await reducedContext.newPage();p.on('pageerror',e=>errors.push(e.message));
 await p.clock.install({time:new Date('2026-10-07T09:00:00Z')});await p.clock.pauseAt(new Date('2026-10-07T09:00:01Z'));
 await p.goto(`http://127.0.0.1:${server.address().port}`,{waitUntil:'domcontentloaded'});await p.locator('#introPlay').click();
 await p.clock.runFor(3500);await p.locator('#progress [data-level="1"]').click();await p.locator('#introPlay').click();
 await p.clock.runFor(5000);assert.equal(await p.locator('.first-tap-hint').count(),0,'Switching levels cancels pending hint');
 await p.locator('#progress [data-level="0"]').click();await p.clock.runFor(4000);
 assert.equal(await p.locator('.first-tap-arrow').evaluate(e=>getComputedStyle(e).animationName),'none','Reduced motion keeps arrow static');
 assert(await p.locator('.first-tap-arrow').isVisible());
 await p.locator('#board [data-i="8"]').click();await p.clock.runFor(5000);assert.equal(await p.locator('.first-tap-hint').count(),0,'Even a quiet first tap permanently dismisses hint');
 await p.locator('#undo').click();await p.clock.runFor(5000);assert.equal(await p.locator('.first-tap-hint').count(),0);
 await reducedContext.close();
 assert.deepEqual(errors,[]);
 console.log('PASS: 7 bursts / 6 waves; one intro; exact 4s hint; pause/resume; first-tap win; replay/undo/reload suppression; level 2 guide; level-switch cancellation; reduced motion; quiet first tap; no runtime errors.');
}finally{await browser.close();server.close()}
